const AppContext = createContext<AppContextType | undefined>(undefined);

export function AppProvider({ children }: { children: React.ReactNode }) {
  const [theme, setTheme] = useState<Theme>("dark");
  const [language, setLanguage] = useState<Language>("en");
  const [uploadedData, setUploadedData] = useState<{ name: string, data: any[], columns: string[] } | null>(null);
  const [analysisInsights, setAnalysisInsights] = useState<any[]>([]);
  const [dashboardStats, setDashboardStats] = useState({ totalDatasets: 0, processedRows: 0, errorsFixed: 0, timeSaved: 0 });
  const [recentUploads, setRecentUploads] = useState<any[]>([]);
  const [reports, setReports] = useState<any[]>([]);

  useEffect(() => {
    const root = window.document.documentElement;
    root.classList.remove("light", "dark");
    root.classList.add(theme);
  }, [theme]);

  const toggleTheme = () => setTheme((prev) => (prev === "dark" ? "light" : "dark"));

  const t = (key: string) => {
    // @ts-ignore
    return translations[language][key] || key;
  };

  return (
    <AppContext.Provider value={{ theme, toggleTheme, language, setLanguage, t, uploadedData, setUploadedData, analysisInsights, setAnalysisInsights, dashboardStats, setDashboardStats, recentUploads, setRecentUploads, reports, setReports }}>
      {children}
    </AppContext.Provider>
  );
}

export function useAppContext() {
  const context = useContext(AppContext);
  if (context === undefined) {
    throw new Error("useAppContext must be used within an AppProvider");
  }
  return context;
}
